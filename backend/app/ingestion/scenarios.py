"""
Named, deterministic scenarios built on top of `telemetry_simulator.py`.

Each scenario takes the plausible baseline generated by the simulator and
applies a targeted, realistic modification to it — never a single absurd
spike (docs Milestone 2, requirement #3/#4). The modification only ever
changes `consumption` (and, where the scenario genuinely implies it,
`occupancy`); it never writes an "this is an anomaly" flag anywhere. The
future Anomaly Engine (Milestone 3) must discover these patterns from the
values and context alone.

Each scenario function returns a `ScenarioResult`, which includes
`reference_windows` — metadata describing what was injected and why. This
metadata is for *tests and development inspection only* (docs Milestone 2,
requirement #14/#18) — it is not written to the database and the API never
exposes it as ground truth.
"""
from __future__ import annotations

from dataclasses import dataclass, field
from datetime import datetime, timedelta, timezone

import pandas as pd

from app.ingestion.telemetry_simulator import SimulatorConfig, _occupancy_fraction, generate_baseline
from app.models.measurement import OperatingStatus
from app.models.resource import ResourceType

SCENARIO_NAMES = [
    "normal_operation",
    "water_leak",
    "electricity_overconsumption",
    "closed_building_consumption",
    "legitimate_spike",
    "post_intervention_recovery",
]


@dataclass
class ReferenceWindow:
    """Development/test-only metadata describing an injected pattern."""

    resource_type: ResourceType
    start: datetime
    end: datetime
    description: str


@dataclass
class ScenarioResult:
    name: str
    config: SimulatorConfig
    measurements: dict[ResourceType, pd.DataFrame]
    reference_windows: list[ReferenceWindow] = field(default_factory=list)


def _default_config() -> SimulatorConfig:
    return SimulatorConfig()


def _generate_all(config: SimulatorConfig) -> dict[ResourceType, pd.DataFrame]:
    return {rt: generate_baseline(config, rt) for rt in (ResourceType.ELECTRICITY, ResourceType.WATER)}


def _nth_weekday_after_start(config: SimulatorConfig, week_offset: int, weekday: int) -> datetime:
    """UTC midnight of the requested weekday, `week_offset` weeks into the run.

    weekday: 0=Monday .. 6=Sunday.
    """
    start = datetime.combine(config.start_date, datetime.min.time(), tzinfo=timezone.utc)
    anchor = start + timedelta(weeks=week_offset)
    days_ahead = (weekday - anchor.weekday()) % 7
    return anchor + timedelta(days=days_ahead)


def _apply_flat_override(
    df: pd.DataFrame, start: datetime, end: datetime, value: float, occupancy: int | None = None
) -> pd.DataFrame:
    """Overwrite consumption (and optionally occupancy) with a flat value in [start, end)."""
    mask = (df["timestamp"] >= start) & (df["timestamp"] < end)
    df.loc[mask, "consumption"] = value
    if occupancy is not None:
        df.loc[mask, "occupancy"] = occupancy
    return df


def _apply_scaled_window(df: pd.DataFrame, start: datetime, end: datetime, factor: float, occupancy_factor: float | None = None) -> pd.DataFrame:
    """Scale existing consumption (and optionally occupancy) within a window — used for
    proportional, plausible increases rather than an arbitrary flat override."""
    mask = (df["timestamp"] >= start) & (df["timestamp"] < end)
    df.loc[mask, "consumption"] = df.loc[mask, "consumption"] * factor
    if occupancy_factor is not None:
        df.loc[mask, "occupancy"] = (df.loc[mask, "occupancy"] * occupancy_factor).round().astype(int)
    return df


def scenario_normal_operation(config: SimulatorConfig | None = None) -> ScenarioResult:
    """Scenario 1 — plausible baseline behavior only, no injected anomaly."""
    config = config or _default_config()
    measurements = _generate_all(config)
    return ScenarioResult(name="normal_operation", config=config, measurements=measurements)


def scenario_water_leak(config: SimulatorConfig | None = None) -> ScenarioResult:
    """
    Scenario 2 — Water leak.

    A sustained, flat, continuous-flow-like elevation in water consumption
    starting exactly at closing time on a chosen weekday and persisting for
    several hours, while occupancy is zero and the building is marked
    closed — evidence-rich (deviation + closed + zero occupancy +
    persistence + flat shape), not a single spike.
    """
    config = config or _default_config()
    measurements = _generate_all(config)

    leak_day = _nth_weekday_after_start(config, week_offset=config.weeks - 1, weekday=2)  # Wednesday, last full week
    window = config.operating_hours.window_for(leak_day.weekday())
    close_hour = window[1] if window else 18.0
    start = leak_day + timedelta(hours=close_hour)
    end = start + timedelta(hours=3)

    water_profile = config.profiles[ResourceType.WATER]
    # Continuous-flow-like leak: a clear multiple of the closed-hours
    # baseline, but not an absurd single-row spike — flat and sustained.
    leak_rate = water_profile.closed_base * 14

    measurements[ResourceType.WATER] = _apply_flat_override(
        measurements[ResourceType.WATER], start, end, value=round(leak_rate, 3), occupancy=0
    )

    windows = [
        ReferenceWindow(
            resource_type=ResourceType.WATER,
            start=start,
            end=end,
            description="Sustained elevated water flow after closing time; occupancy=0, operating_status=closed.",
        )
    ]
    return ScenarioResult(name="water_leak", config=config, measurements=measurements, reference_windows=windows)


def scenario_electricity_overconsumption(config: SimulatorConfig | None = None) -> ScenarioResult:
    """
    Scenario 3 — Electricity overconsumption.

    Equipment/HVAC plausibly left running past closing time: electricity
    stays at a meaningful (not implausibly extreme) fraction of the daytime
    peak for several hours after close, rather than dropping to standby.
    """
    config = config or _default_config()
    measurements = _generate_all(config)

    anomaly_day = _nth_weekday_after_start(config, week_offset=config.weeks - 2, weekday=1)  # Tuesday
    window = config.operating_hours.window_for(anomaly_day.weekday())
    close_hour = window[1] if window else 18.0
    start = anomaly_day + timedelta(hours=close_hour)
    end = start + timedelta(hours=4)

    elec_profile = config.profiles[ResourceType.ELECTRICITY]
    # Plausible partial-load leftover (e.g. HVAC + lighting on one zone),
    # not the full daytime peak.
    lingering_rate = elec_profile.closed_base + 0.5 * (elec_profile.open_peak - elec_profile.closed_base)

    measurements[ResourceType.ELECTRICITY] = _apply_flat_override(
        measurements[ResourceType.ELECTRICITY], start, end, value=round(lingering_rate, 3), occupancy=0
    )

    windows = [
        ReferenceWindow(
            resource_type=ResourceType.ELECTRICITY,
            start=start,
            end=end,
            description="Elevated electricity draw persisting after closing time; occupancy=0, operating_status=closed.",
        )
    ]
    return ScenarioResult(
        name="electricity_overconsumption", config=config, measurements=measurements, reference_windows=windows
    )


def scenario_closed_building_consumption(config: SimulatorConfig | None = None) -> ScenarioResult:
    """
    Scenario 4 — Building closed but consumption continues, for a full day.

    On a day the building is fully closed (a Saturday), both electricity
    and water instead follow a weekday-like occupancy-driven curve — as if
    equipment were left on a weekday schedule. This is a distinct evidence
    pattern from Scenarios 2/3 (whole-day pattern break vs. a single
    after-hours window).
    """
    config = config or _default_config()
    measurements = _generate_all(config)

    saturday = _nth_weekday_after_start(config, week_offset=config.weeks - 3, weekday=5)
    day_start = saturday
    day_end = saturday + timedelta(days=1)

    # Re-run the weekday occupancy/consumption shape (Monday's schedule)
    # onto this Saturday's timestamps, but keep occupancy at 0 and
    # operating_status CLOSED — the resource behaves as if equipment were
    # left running on a weekday timer while nobody is actually present.
    monday_window = config.operating_hours.window_for(0)

    for resource_type in (ResourceType.ELECTRICITY, ResourceType.WATER):
        df = measurements[resource_type]
        profile = config.profiles[resource_type]
        mask = (df["timestamp"] >= day_start) & (df["timestamp"] < day_end)
        for idx in df.index[mask]:
            hour = df.loc[idx, "timestamp"].hour
            occ_fraction = _occupancy_fraction(hour, monday_window)
            df.loc[idx, "consumption"] = round(
                profile.closed_base + (profile.open_peak - profile.closed_base) * occ_fraction, 3
            )
            df.loc[idx, "occupancy"] = 0  # nobody is actually there
            df.loc[idx, "operating_status"] = OperatingStatus.CLOSED
        measurements[resource_type] = df

    windows = [
        ReferenceWindow(
            resource_type=rt,
            start=day_start,
            end=day_end,
            description="Weekday-shaped consumption on a day the building is closed; occupancy=0 throughout.",
        )
        for rt in (ResourceType.ELECTRICITY, ResourceType.WATER)
    ]
    return ScenarioResult(
        name="closed_building_consumption", config=config, measurements=measurements, reference_windows=windows
    )


def scenario_legitimate_spike(config: SimulatorConfig | None = None) -> ScenarioResult:
    """
    Scenario 5 — Legitimate temporary spike.

    An occupied event (e.g. a school function) legitimately raises both
    occupancy and consumption for a few hours during normal operating
    hours, then returns to the usual pattern. Because occupancy explains
    the rise, this should NOT later be classified `operationally_suspicious`
    by the anomaly engine, even though it is statistically `unusual`.
    """
    config = config or _default_config()
    measurements = _generate_all(config)

    event_day = _nth_weekday_after_start(config, week_offset=config.weeks - 4, weekday=4)  # Friday
    window = config.operating_hours.window_for(event_day.weekday())
    open_hour = window[0] if window else 8.0
    start = event_day + timedelta(hours=open_hour + 4)  # early afternoon
    end = start + timedelta(hours=3)

    for resource_type in (ResourceType.ELECTRICITY, ResourceType.WATER):
        measurements[resource_type] = _apply_scaled_window(
            measurements[resource_type], start, end, factor=1.8, occupancy_factor=1.8
        )

    windows = [
        ReferenceWindow(
            resource_type=rt,
            start=start,
            end=end,
            description="Temporary, occupancy-consistent increase during an event; returns to normal afterward.",
        )
        for rt in (ResourceType.ELECTRICITY, ResourceType.WATER)
    ]
    return ScenarioResult(name="legitimate_spike", config=config, measurements=measurements, reference_windows=windows)


def scenario_post_intervention_recovery(config: SimulatorConfig | None = None) -> ScenarioResult:
    """
    Scenario 6 — Post-intervention recovery.

    Builds on the water-leak scenario: the leak occurs as in Scenario 2,
    then — after a marked "intervention" point — the following day's data
    returns to the normal closed-hours baseline. This is the full timeline
    used for the judging demo (docs/DEMO.md): baseline weeks, an anomaly,
    then verified recovery.
    """
    config = config or _default_config()
    leak_result = scenario_water_leak(config)
    measurements = leak_result.measurements
    leak_window = leak_result.reference_windows[0]

    intervention_at = leak_window.end  # intervention marked immediately after the leak window
    recovery_start = intervention_at
    recovery_end = recovery_start + timedelta(days=1)

    # Post-intervention: closed-hours water consumption for the next day
    # returns to the ordinary near-zero baseline. We don't need to inject
    # anything here — the underlying baseline generator already produces
    # that behavior; the leak scenario only overrode the single incident
    # window, so "recovery" is really just confirming no further override
    # is applied going forward. This is intentional: recovery should look
    # like the return of ordinary behavior, not a second engineered event.
    windows = leak_result.reference_windows + [
        ReferenceWindow(
            resource_type=ResourceType.WATER,
            start=recovery_start,
            end=recovery_end,
            description="Post-intervention window: water consumption returns to the ordinary closed-hours baseline.",
        )
    ]
    return ScenarioResult(
        name="post_intervention_recovery", config=config, measurements=measurements, reference_windows=windows
    )


SCENARIOS = {
    "normal_operation": scenario_normal_operation,
    "water_leak": scenario_water_leak,
    "electricity_overconsumption": scenario_electricity_overconsumption,
    "closed_building_consumption": scenario_closed_building_consumption,
    "legitimate_spike": scenario_legitimate_spike,
    "post_intervention_recovery": scenario_post_intervention_recovery,
}


def generate_scenario(name: str, config: SimulatorConfig | None = None) -> ScenarioResult:
    """Look up and run a named scenario. Raises KeyError with the valid names on typo."""
    if name not in SCENARIOS:
        raise KeyError(f"Unknown scenario '{name}'. Valid scenarios: {sorted(SCENARIOS)}")
    return SCENARIOS[name](config)
